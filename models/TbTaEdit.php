    // Validate form
    protected function validateForm()
    {
        global $Language;

        // Check if validation required
        if (!Config("SERVER_VALIDATE")) {
            return true;
        }
        $validateForm = true;
        if ($this->ta_id->Required) {
            if (!$this->ta_id->IsDetailKey && EmptyValue($this->ta_id->FormValue)) {
                $this->ta_id->addErrorMessage(str_replace("%s", $this->ta_id->caption(), $this->ta_id->RequiredErrorMessage));
            }
        }
        if ($this->taprefic_name->Required) {
            if (!$this->taprefic_name->IsDetailKey && EmptyValue($this->taprefic_name->FormValue)) {
                $this->taprefic_name->addErrorMessage(str_replace("%s", $this->taprefic_name->caption(), $this->taprefic_name->RequiredErrorMessage));
            }
        }
        if (!CheckInteger($this->taprefic_name->FormValue)) {
            $this->taprefic_name->addErrorMessage($this->taprefic_name->getErrorMessage(false));
        }
        if ($this->ta_name->Required) {
            if (!$this->ta_name->IsDetailKey && EmptyValue($this->ta_name->FormValue)) {
                $this->ta_name->addErrorMessage(str_replace("%s", $this->ta_name->caption(), $this->ta_name->RequiredErrorMessage));
            }
        }
        if ($this->ta_surname->Required) {
            if (!$this->ta_surname->IsDetailKey && EmptyValue($this->ta_surname->FormValue)) {
                $this->ta_surname->addErrorMessage(str_replace("%s", $this->ta_surname->caption(), $this->ta_surname->RequiredErrorMessage));
            }
        }
        if ($this->ta_studentcode->Required) {
            if (!$this->ta_studentcode->IsDetailKey && EmptyValue($this->ta_studentcode->FormValue)) {
                $this->ta_studentcode->addErrorMessage(str_replace("%s", $this->ta_studentcode->caption(), $this->ta_studentcode->RequiredErrorMessage));
            }
        }

        // Return validate result
        $validateForm = $validateForm && !$this->hasInvalidFields();

        // Call Form_CustomValidate event
        $formCustomError = "";
        $validateForm = $validateForm && $this->formCustomValidate($formCustomError);
        if ($formCustomError != "") {
            $this->setFailureMessage($formCustomError);
        }
        return $validateForm;
    }

    // Update record based on key values
    protected function editRow()
    {
        global $Security, $Language;
        $oldKeyFilter = $this->getRecordFilter();
        $filter = $this->applyUserIDFilters($oldKeyFilter);
        $conn = $this->getConnection();
        $this->CurrentFilter = $filter;
        $sql = $this->getCurrentSql();
        $rsold = $conn->fetchAssociative($sql);
        if (!$rsold) {
            $this->setFailureMessage($Language->phrase("NoRecord")); // Set no record message
            $editRow = false; // Update Failed
        } else {
            // Save old values
            $this->loadDbValues($rsold);
            $rsnew = [];

            // taprefic_name
            $this->taprefic_name->setDbValueDef($rsnew, $this->taprefic_name->CurrentValue, 0, $this->taprefic_name->ReadOnly);

            // ta_name
            $this->ta_name->setDbValueDef($rsnew, $this->ta_name->CurrentValue, "", $this->ta_name->ReadOnly);

            // ta_surname
            $this->ta_surname->setDbValueDef($rsnew, $this->ta_surname->CurrentValue, "", $this->ta_surname->ReadOnly);

            // ta_studentcode
            if ($this->ta_studentcode->getSessionValue() != "") {
                $this->ta_studentcode->ReadOnly = true;
            }
            $this->ta_studentcode->setDbValueDef($rsnew, $this->ta_studentcode->CurrentValue, "", $this->ta_studentcode->ReadOnly);

            // Call Row Updating event
            $updateRow = $this->rowUpdating($rsold, $rsnew);
            if ($updateRow) {
                if (count($rsnew) > 0) {
                    $editRow = $this->update($rsnew, "", $rsold);
                } else {
                    $editRow = true; // No field to update
                }
                if ($editRow) {
                }
            } else {
                if ($this->getSuccessMessage() != "" || $this->getFailureMessage() != "") {
                    // Use the message, do nothing
                } elseif ($this->CancelMessage != "") {
                    $this->setFailureMessage($this->CancelMessage);
                    $this->CancelMessage = "";
                } else {
                    $this->setFailureMessage($Language->phrase("UpdateCancelled"));
                }
                $editRow = false;
            }
        }

        // Call Row_Updated event
        if ($editRow) {
            $this->rowUpdated($rsold, $rsnew);
        }

        // Clean upload path if any
        if ($editRow) {
        }

        // Write JSON for API request
        if (IsApi() && $editRow) {
            $row = $this->getRecordsFromRecordset([$rsnew], true);
            WriteJson(["success" => true, $this->TableVar => $row]);
        }
        return $editRow;
    }

    // Set up master/detail based on QueryString
    protected function setupMasterParms()
    {
        $validMaster = false;
        // Get the keys for master table
        if (($master = Get(Config("TABLE_SHOW_MASTER"), Get(Config("TABLE_MASTER")))) !== null) {
            $masterTblVar = $master;
            if ($masterTblVar == "") {
                $validMaster = true;
                $this->DbMasterFilter = "";
                $this->DbDetailFilter = "";
            }
            if ($masterTblVar == "students") {
                $validMaster = true;
                $masterTbl = Container("students");
                if (($parm = Get("fk_student_code", Get("ta_studentcode"))) !== null) {
                    $masterTbl->student_code->setQueryStringValue($parm);
                    $this->ta_studentcode->setQueryStringValue($masterTbl->student_code->QueryStringValue);
                    $this->ta_studentcode->setSessionValue($this->ta_studentcode->QueryStringValue);
                } else {
                    $validMaster = false;
                }
            }
        } elseif (($master = Post(Config("TABLE_SHOW_MASTER"), Post(Config("TABLE_MASTER")))) !== null) {
            $masterTblVar = $master;
            if ($masterTblVar == "") {
                    $validMaster = true;
                    $this->DbMasterFilter = "";
                    $this->DbDetailFilter = "";
            }
            if ($masterTblVar == "students") {
                $validMaster = true;
                $masterTbl = Container("students");
                if (($parm = Post("fk_student_code", Post("ta_studentcode"))) !== null) {
                    $masterTbl->student_code->setFormValue($parm);
                    $this->ta_studentcode->setFormValue($masterTbl->student_code->FormValue);
                    $this->ta_studentcode->setSessionValue($this->ta_studentcode->FormValue);
                } else {
                    $validMaster = false;
                }
            }
        }
        if ($validMaster) {
            // Save current master table
            $this->setCurrentMasterTable($masterTblVar);
            $this->setSessionWhere($this->getDetailFilterFromSession());

            // Reset start record counter (new master key)
            if (!$this->isAddOrEdit()) {
                $this->StartRecord = 1;
                $this->setStartRecordNumber($this->StartRecord);
            }

            // Clear previous master key from Session
            if ($masterTblVar != "students") {
                if ($this->ta_studentcode->CurrentValue == "") {
                    $this->ta_studentcode->setSessionValue("");
                }
            }
        }
        $this->DbMasterFilter = $this->getMasterFilterFromSession(); // Get master filter from session
        $this->DbDetailFilter = $this->getDetailFilterFromSession(); // Get detail filter from session
    }

