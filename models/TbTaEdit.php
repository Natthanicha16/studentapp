        // Check field name 'taprefic_name' first before field var 'x_taprefic_name'
        $val = $CurrentForm->hasValue("taprefic_name") ? $CurrentForm->getValue("taprefic_name") : $CurrentForm->getValue("x_taprefic_name");
        if (!$this->taprefic_name->IsDetailKey) {
            if (IsApi() && $val === null) {
                $this->taprefic_name->Visible = false; // Disable update for API request
            } else {
                $this->taprefic_name->setFormValue($val, true, $validate);
            }
        }

        // Check field name 'ta_name' first before field var 'x_ta_name'
        $val = $CurrentForm->hasValue("ta_name") ? $CurrentForm->getValue("ta_name") : $CurrentForm->getValue("x_ta_name");
        if (!$this->ta_name->IsDetailKey) {
            if (IsApi() && $val === null) {
                $this->ta_name->Visible = false; // Disable update for API request
            } else {
                $this->ta_name->setFormValue($val);
            }
        }

