     * @param string|array $where WHERE clause
     * @param string $curfilter Filter
     * @return QueryBuilder
     */
    public function updateSql(&$rs, $where = "", $curfilter = true)
    {
        $queryBuilder = $this->getQueryBuilder();
        $queryBuilder->update($this->UpdateTable);
        foreach ($rs as $name => $value) {
            if (!isset($this->Fields[$name]) || $this->Fields[$name]->IsCustom || $this->Fields[$name]->IsAutoIncrement) {
                continue;
            }
            $type = GetParameterType($this->Fields[$name], $value, $this->Dbid);
            $queryBuilder->set($this->Fields[$name]->Expression, $queryBuilder->createPositionalParameter($value, $type));
        }
        $filter = ($curfilter) ? $this->CurrentFilter : "";
        if (is_array($where)) {
            $where = $this->arrayToFilter($where);
        }
        AddFilter($filter, $where);
        if ($filter != "") {
            $queryBuilder->where($filter);
        }
        return $queryBuilder;
    }

    // Update
    public function update(&$rs, $where = "", $rsold = null, $curfilter = true)
    {
        // Cascade Update detail table 'tbstudy'
        $cascadeUpdate = false;
        $rscascade = [];
        if ($rsold && (isset($rs['student_code']) && $rsold['student_code'] != $rs['student_code'])) { // Update detail field 'study_studentcode'
            $cascadeUpdate = true;
            $rscascade['study_studentcode'] = $rs['student_code'];
        }
        if ($cascadeUpdate) {
            $rswrk = Container("tbstudy")->loadRs("`study_studentcode` = " . QuotedValue($rsold['student_code'], DATATYPE_STRING, 'DB'))->fetchAllAssociative();
            foreach ($rswrk as $rsdtlold) {
                $rskey = [];
                $fldname = 'study_id';
                $rskey[$fldname] = $rsdtlold[$fldname];
                $rsdtlnew = array_merge($rsdtlold, $rscascade);
                // Call Row_Updating event
                $success = Container("tbstudy")->rowUpdating($rsdtlold, $rsdtlnew);
                if ($success) {
                    $success = Container("tbstudy")->update($rscascade, $rskey, $rsdtlold);
                }
                if (!$success) {
                    return false;
                }
                // Call Row_Updated event
                Container("tbstudy")->rowUpdated($rsdtlold, $rsdtlnew);
            }
        }

        // Cascade Update detail table 'address'
        $cascadeUpdate = false;
        $rscascade = [];
        if ($rsold && (isset($rs['student_code']) && $rsold['student_code'] != $rs['student_code'])) { // Update detail field 'address_studentcode'
            $cascadeUpdate = true;
            $rscascade['address_studentcode'] = $rs['student_code'];
        }
        if ($cascadeUpdate) {
            $rswrk = Container("address")->loadRs("`address_studentcode` = " . QuotedValue($rsold['student_code'], DATATYPE_STRING, 'DB'))->fetchAllAssociative();
            foreach ($rswrk as $rsdtlold) {
                $rskey = [];
                $fldname = 'address_id';
                $rskey[$fldname] = $rsdtlold[$fldname];
                $rsdtlnew = array_merge($rsdtlold, $rscascade);
                // Call Row_Updating event
                $success = Container("address")->rowUpdating($rsdtlold, $rsdtlnew);
                if ($success) {
                    $success = Container("address")->update($rscascade, $rskey, $rsdtlold);
                }
                if (!$success) {
                    return false;
                }
                // Call Row_Updated event
                Container("address")->rowUpdated($rsdtlold, $rsdtlnew);
            }
        }

        // If no field is updated, execute may return 0. Treat as success
        $success = $this->updateSql($rs, $where, $curfilter)->execute();
        $success = ($success > 0) ? $success : true;
        return $success;
    }

